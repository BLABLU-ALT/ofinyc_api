-- OFICYNIC script completo do banco PostgreSQL
-- Equivale as migracoes Flyway V1 a V9
-- Nao usado pela aplicacao
-- Uso psql -d banco_vazio -f docs/banco/script-completo.sql

BEGIN;

-- Clientes
CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    cpf VARCHAR(11) NOT NULL CONSTRAINT uk_clientes_cpf UNIQUE,
    telefone VARCHAR(20),
    email VARCHAR(160),
    endereco VARCHAR(255)
);

-- Motocicletas
-- Exige placa ou chassi
-- cliente_id guarda o proprietario atual
CREATE TABLE motocicletas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR(7) CONSTRAINT uk_motocicletas_placa UNIQUE,
    chassi VARCHAR(17) CONSTRAINT uk_motocicletas_chassi UNIQUE,
    marca VARCHAR(80) NOT NULL,
    modelo VARCHAR(100) NOT NULL,
    ano INTEGER NOT NULL CHECK (ano BETWEEN 1900 AND 2100),
    cor VARCHAR(50),
    cliente_id BIGINT REFERENCES clientes(id),
    CONSTRAINT ck_motocicletas_identificacao CHECK (
        (placa IS NOT NULL OR chassi IS NOT NULL)
        AND (placa IS NULL OR btrim(placa) <> '')
        AND (chassi IS NULL OR btrim(chassi) <> '')
    )
);
CREATE INDEX idx_motocicletas_cliente ON motocicletas(cliente_id);

-- Produtos
-- estoque guarda o saldo fisico
-- Empenho calculado pelas OS abertas
CREATE TABLE produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL CONSTRAINT uk_produtos_codigo UNIQUE,
    descricao VARCHAR(180) NOT NULL,
    preco_venda NUMERIC(14,2) NOT NULL CHECK (preco_venda >= 0),
    unidade_medida VARCHAR(12),
    estoque NUMERIC(15,3) NOT NULL DEFAULT 0 CHECK (estoque >= 0),
    CONSTRAINT ck_produto_unidade CHECK (unidade_medida IS NULL OR length(trim(unidade_medida)) > 0)
);

-- Servicos
CREATE TABLE servicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    descricao VARCHAR(255),
    preco NUMERIC(14,2) NOT NULL CHECK (preco >= 0)
);

-- Funcionarios responsaveis por OS e movimentacoes
CREATE TABLE funcionarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL CHECK (length(trim(nome)) > 0)
);

-- Ordens de servico
CREATE TABLE ordens_servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255) NOT NULL,
    data_abertura DATE NOT NULL,
    cliente_id BIGINT REFERENCES clientes(id),
    motocicleta_id BIGINT REFERENCES motocicletas(id),
    situacao VARCHAR(20) NOT NULL DEFAULT 'ORCAMENTO',
    data_finalizacao DATE,
    funcionario_id BIGINT REFERENCES funcionarios(id),
    ordem_origem_id BIGINT REFERENCES ordens_servico(id),
    data_criacao DATE,
    data_aprovacao DATE,
    data_abertura_anterior DATE,
    CONSTRAINT ck_os_situacao CHECK (
        situacao IN ('ORCAMENTO', 'CANCELADA', 'EM_ANDAMENTO', 'CONCLUIDA', 'RETRABALHO')
    ),
    CONSTRAINT ck_os_finalizacao CHECK (
        (situacao = 'CONCLUIDA' AND data_finalizacao IS NOT NULL)
        OR (situacao <> 'CONCLUIDA' AND data_finalizacao IS NULL)
    ),
    CONSTRAINT ck_os_origem CHECK (ordem_origem_id IS NULL OR ordem_origem_id <> id),
    CONSTRAINT ck_os_retrabalho_origem CHECK (situacao <> 'RETRABALHO' OR ordem_origem_id IS NOT NULL)
);
CREATE INDEX idx_ordens_servico_cliente ON ordens_servico(cliente_id);
CREATE INDEX idx_ordens_servico_motocicleta ON ordens_servico(motocicleta_id);
CREATE INDEX idx_os_funcionario ON ordens_servico(funcionario_id);
CREATE INDEX idx_os_origem ON ordens_servico(ordem_origem_id);
COMMENT ON COLUMN ordens_servico.data_abertura_anterior IS 'Data registrada antes da aprovação de OS legada; não comprova a data de criação';

-- Itens de servico da OS
-- valor_unitario guarda o preco cobrado
CREATE TABLE itens_servico_os (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id BIGINT NOT NULL REFERENCES ordens_servico(id),
    servico_id BIGINT NOT NULL REFERENCES servicos(id),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    valor_unitario NUMERIC(14,2) NOT NULL CHECK (valor_unitario >= 0)
);
CREATE INDEX idx_itens_servico_os_ordem ON itens_servico_os(ordem_servico_id);
CREATE INDEX idx_itens_servico_os_servico ON itens_servico_os(servico_id);

-- Itens de produto da OS
-- Quantidade fica reservada enquanto a OS esta aberta
CREATE TABLE itens_produto_os (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id BIGINT NOT NULL REFERENCES ordens_servico(id),
    produto_id BIGINT NOT NULL REFERENCES produtos(id),
    quantidade NUMERIC(15,3) NOT NULL CHECK (quantidade > 0),
    valor_unitario NUMERIC(14,2) NOT NULL CHECK (valor_unitario >= 0),
    unidade_medida VARCHAR(12) NOT NULL CHECK (length(trim(unidade_medida)) > 0)
);
CREATE INDEX idx_item_produto_os ON itens_produto_os(ordem_servico_id);
CREATE INDEX idx_item_produto_produto ON itens_produto_os(produto_id);

-- Movimentacoes de estoque
-- Saida da OS gerada pelo sistema na conclusao
CREATE TABLE movimentacoes_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT NOT NULL REFERENCES produtos(id),
    funcionario_id BIGINT NOT NULL REFERENCES funcionarios(id),
    ordem_servico_id BIGINT REFERENCES ordens_servico(id),
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('ENTRADA', 'SAIDA')),
    quantidade NUMERIC(15,3) NOT NULL CHECK (quantidade > 0),
    unidade_medida VARCHAR(12) NOT NULL CHECK (length(trim(unidade_medida)) > 0),
    data TIMESTAMP WITH TIME ZONE NOT NULL,
    motivo VARCHAR(255) NOT NULL CHECK (length(trim(motivo)) > 0),
    usuario_atuante VARCHAR(255) NOT NULL CHECK (length(trim(usuario_atuante)) > 0),
    CONSTRAINT ck_movimento_os CHECK (ordem_servico_id IS NULL OR tipo = 'SAIDA')
);
CREATE INDEX idx_movimento_produto ON movimentacoes_estoque(produto_id);
CREATE INDEX idx_movimento_funcionario ON movimentacoes_estoque(funcionario_id);
CREATE INDEX idx_movimento_os ON movimentacoes_estoque(ordem_servico_id);

COMMIT;
