-- O proprietário dos cadastros antigos será informado pelo usuário, sem inferência.
ALTER TABLE motocicletas ADD COLUMN cliente_id BIGINT REFERENCES clientes(id);
CREATE INDEX idx_motocicletas_cliente ON motocicletas(cliente_id);

ALTER TABLE ordens_servico
    ADD COLUMN situacao VARCHAR(20) NOT NULL DEFAULT 'ABERTA',
    ADD COLUMN data_finalizacao DATE,
    ADD CONSTRAINT ck_os_situacao CHECK (situacao IN ('ABERTA', 'EM_ANDAMENTO', 'FINALIZADA')),
    ADD CONSTRAINT ck_os_finalizacao CHECK (
        (situacao = 'FINALIZADA' AND data_finalizacao IS NOT NULL)
        OR (situacao <> 'FINALIZADA' AND data_finalizacao IS NULL)
    );

CREATE TABLE itens_servico_os (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id BIGINT NOT NULL REFERENCES ordens_servico(id),
    servico_id BIGINT NOT NULL REFERENCES servicos(id),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    valor_unitario NUMERIC(14,2) NOT NULL CHECK (valor_unitario >= 0)
);
CREATE INDEX idx_itens_servico_os_ordem ON itens_servico_os(ordem_servico_id);
CREATE INDEX idx_itens_servico_os_servico ON itens_servico_os(servico_id);
