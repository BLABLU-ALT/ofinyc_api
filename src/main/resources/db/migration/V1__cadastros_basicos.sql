CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    cpf VARCHAR(11) NOT NULL CONSTRAINT uk_clientes_cpf UNIQUE,
    telefone VARCHAR(20), email VARCHAR(160), endereco VARCHAR(255)
);
CREATE TABLE motocicletas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR(7) NOT NULL CONSTRAINT uk_motocicletas_placa UNIQUE,
    chassi VARCHAR(17) NOT NULL CONSTRAINT uk_motocicletas_chassi UNIQUE,
    marca VARCHAR(80) NOT NULL, modelo VARCHAR(100) NOT NULL,
    ano INTEGER NOT NULL CHECK (ano BETWEEN 1900 AND 2100), cor VARCHAR(50)
);
CREATE TABLE produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL CONSTRAINT uk_produtos_codigo UNIQUE,
    descricao VARCHAR(180) NOT NULL,
    preco_venda NUMERIC(14,2) NOT NULL CHECK (preco_venda >= 0)
);
CREATE TABLE servicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL, descricao VARCHAR(255),
    preco NUMERIC(14,2) NOT NULL CHECK (preco >= 0)
);
