CREATE TABLE funcionarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL CHECK (length(trim(nome)) > 0)
);
ALTER TABLE ordens_servico ADD COLUMN funcionario_id BIGINT REFERENCES funcionarios(id);
CREATE INDEX idx_os_funcionario ON ordens_servico(funcionario_id);
-- Legado sem unidade/responsável permanece consultável, sem atribuição fictícia.
ALTER TABLE produtos ADD COLUMN unidade_medida VARCHAR(12);
ALTER TABLE produtos ADD CONSTRAINT ck_produto_unidade CHECK (unidade_medida IS NULL OR length(trim(unidade_medida)) > 0);
-- Empenho é derivado dos itens de OS não finalizadas; não há contador duplicado.
ALTER TABLE produtos ADD COLUMN estoque NUMERIC(15,3) NOT NULL DEFAULT 0 CHECK (estoque >= 0);
CREATE TABLE itens_produto_os (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id BIGINT NOT NULL REFERENCES ordens_servico(id),
    produto_id BIGINT NOT NULL REFERENCES produtos(id),
    quantidade NUMERIC(15,3) NOT NULL CHECK (quantidade > 0),
    valor_unitario NUMERIC(14,2) NOT NULL CHECK (valor_unitario >= 0),
    unidade_medida VARCHAR(12) NOT NULL CHECK (length(trim(unidade_medida)) > 0)
);
CREATE INDEX idx_item_produto_os ON itens_produto_os(ordem_servico_id);
CREATE INDEX idx_item_produto_produto ON itens_produto_os(produto_id);
CREATE TABLE movimentacoes_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT NOT NULL REFERENCES produtos(id),
    funcionario_id BIGINT NOT NULL REFERENCES funcionarios(id),
    ordem_servico_id BIGINT REFERENCES ordens_servico(id),
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('ENTRADA', 'SAIDA')),
    quantidade NUMERIC(15,3) NOT NULL CHECK (quantidade > 0),
    unidade_medida VARCHAR(12) NOT NULL CHECK (length(trim(unidade_medida)) > 0),
    data TIMESTAMP WITH TIME ZONE NOT NULL,
    motivo VARCHAR(255) NOT NULL CHECK (length(trim(motivo)) > 0),
    usuario_atuante VARCHAR(255) NOT NULL CHECK (length(trim(usuario_atuante)) > 0),
    CONSTRAINT ck_movimento_os CHECK (ordem_servico_id IS NULL OR tipo = 'SAIDA')
);
CREATE INDEX idx_movimento_produto ON movimentacoes_estoque(produto_id);
CREATE INDEX idx_movimento_funcionario ON movimentacoes_estoque(funcionario_id);
CREATE INDEX idx_movimento_os ON movimentacoes_estoque(ordem_servico_id);
